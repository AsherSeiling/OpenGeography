// Bibliography formatting for the project's data sources: an APA-style
// reference with the date accessed, plus Markdown (annotated bibliography)
// and BibTeX exports.
import type { Citation, SourceEntry } from "../ipc/api";

/** "22 October 2026" from "2026-10-22". */
export function longDate(iso: string): string {
  const [y, m, d] = iso.split("-").map(Number);
  if (!y || !m || !d) return iso;
  const months = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
  return `${d} ${months[m - 1]} ${y}`;
}

const end = (s: string) => (/[.?!]$/.test(s) ? s : `${s}.`);

/**
 * APA-style reference:
 * Author. (Year). *Title* [Version]. Publisher. Retrieved 22 October 2026, from URL
 * Returns plain text and the italic title separately so callers can style it.
 */
export function reference(c: Citation, accessed: string): { before: string; title: string; after: string } {
  const author = c.author.trim() || "[Author unknown]";
  const year = c.year.trim() || "n.d.";
  const before = `${end(author)} (${year}). `;
  const title = c.title.trim() || "[Untitled]";
  let after = c.version.trim() ? ` [${c.version.trim()}]. ` : ". ";
  const publisher = c.publisher.trim();
  if (publisher && publisher !== author) after += `${end(publisher)} `;
  if (c.url.trim()) after += `Retrieved ${longDate(accessed)}, from ${c.url.trim()}`;
  else if (c.kind === "Local file") after += `Local file, used ${longDate(accessed)}.`;
  return { before, title, after: after.trimEnd() };
}

export function referenceText(c: Citation, accessed: string): string {
  const r = reference(c, accessed);
  return `${r.before}${r.title}${r.after}`;
}

function usedFor(e: SourceEntry): string {
  const names = [...new Set(e.uses.map((u) => u.layerName))];
  return names.length ? `Used for: ${names.join("; ")}.` : "";
}

/** Annotated bibliography in Markdown, sorted by author then title (APA order). */
export function toMarkdown(entries: SourceEntry[], project: string): string {
  // Entries without an author go last.
  const sorted = [...entries].sort(
    (a, b) => Number(!a.citation.author) - Number(!b.citation.author) || a.citation.author.localeCompare(b.citation.author) || a.citation.title.localeCompare(b.citation.title),
  );
  const lines = [`# Data sources — ${project}`, "", `Annotated bibliography generated by GIS Studio on ${longDate(new Date().toISOString().slice(0, 10))}.`, ""];
  for (const e of sorted) {
    const r = reference(e.citation, e.firstUsed);
    lines.push(`${r.before}*${r.title}*${r.after}`, "");
    const notes = [e.citation.annotation.trim(), usedFor(e), e.citation.license.trim() ? `License: ${e.citation.license.trim()}` : ""].filter(Boolean);
    if (notes.length) lines.push(`> ${notes.join(" ")}`, "");
  }
  return lines.join("\n");
}

const bibEscape = (s: string) => s.replace(/([{}&%$#_])/g, "\\$1");

/** BibTeX @misc entries (biblatex-friendly `urldate`). */
export function toBibtex(entries: SourceEntry[]): string {
  const used = new Set<string>();
  return entries
    .map((e) => {
      const c = e.citation;
      let key = (c.key.startsWith("file:") ? `file-${c.title}` : c.key).replace(/[^A-Za-z0-9-]+/g, "-").replace(/^-|-$/g, "").toLowerCase() || "source";
      for (let i = 2; used.has(key); i++) key = `${key.replace(/-\d+$/, "")}-${i}`;
      used.add(key);
      const fields: [string, string][] = [
        ["author", c.author ? `{${bibEscape(c.author)}}` : ""],
        ["title", bibEscape(c.title)],
        ["year", c.year && c.year !== "n.d." ? c.year : ""],
        ["edition", bibEscape(c.version)],
        ["publisher", bibEscape(c.publisher)],
        ["howpublished", c.url ? `\\url{${c.url}}` : ""],
        ["url", c.url],
        ["urldate", e.firstUsed],
        ["note", bibEscape([c.annotation, usedFor(e), c.license ? `License: ${c.license}` : ""].filter(Boolean).join(" "))],
      ];
      const body = fields.filter(([, v]) => v).map(([k, v]) => `  ${k} = {${v}}`).join(",\n");
      return `@misc{${key},\n${body}\n}`;
    })
    .join("\n\n");
}
