import { describe, expect, it } from "vitest";
import { pySubsetSql, type SubsetField } from "./pySubset";
import { pyToSql } from "./pyToSql";

// The table the engine test (crates/engine/tests/pyconformance.rs) runs every case against, with nulls, zeros, empty text and a case twin.
export const FIELDS: SubsetField[] = [
  { name: "id", type: "INTEGER" },
  { name: "name", type: "VARCHAR" },
  { name: "n", type: "BIGINT" },
  { name: "x", type: "DOUBLE" },
];
export const ROWS: (number | string | null)[][] = [
  [1, "a", 1, 1.5],
  [2, "b", 0, 0.0],
  [3, null, null, null],
  [4, "", -1, 3.0],
  [5, "A", 3, 1.0],
  [6, "a", 3, null],
];

/** `$n == 1` is written for short; the script and the SQL are made from `row["n"] == 1`. */
const script = (e: string) => `def calculate(row):\n    return ${e.replace(/\$(\w+)/g, 'row["$1"]')}\n`;

/** Accepted: the translator gives SQL, and CPython and DuckDB must pick the same rows. (`$n` stands for `row["n"]`.) */
const ACCEPT = [
  "$n == 1", "$n == 0", "$n == -1", "$x == 0", "$x == 1.5", "$x == 3", "$name == 'a'", "$name == ''", '$name == "A"',
  "$n in [1, 3]", "$n in [0]", "$x in [0, 1.0]", "$name in ['a', 'b']", "$name in ['a',]",
  "$n is None", "$n is not None", "$name is None", "$name is not None", "$x is None",
  "$n == 1 or $n == 3", "$n == 3 and $name == 'a'", "$n == 3 and $x is None", "$name is None or $n == 1",
  "($n == 1 or $n == 3) and $name is not None", "$n is None or $x is None", "$name == 'a' and ($n == 3 or $n is None)",
];

/** Rejected: outside the subset, so they go to CPython. `differs` = the SQL meaning really is different (the engine test shows it). */
const REJECT: { expr: string; differs?: boolean }[] = [
  { expr: "$n > 0", differs: true }, // None > 0 raises in Python, NULL in SQL
  { expr: "$n >= 3", differs: true },
  { expr: "$n != 1", differs: true }, // True for None in Python, NULL (not kept) in SQL
  { expr: "$name != 'a'", differs: true },
  { expr: "not $n == 1", differs: true },
  { expr: "not ($n == 1 or $n == 3)", differs: true },
  { expr: "$n not in [1, 3]", differs: true },
  { expr: "$name.startswith('a')", differs: true }, // None.startswith raises
  { expr: "'a' in $name", differs: true }, // TypeError on None
  { expr: "1 / $x > 1", differs: true }, // ZeroDivisionError, and None
  { expr: "$n / $x == 1", differs: true },
  { expr: "$n + 1 == 2", differs: true },
  { expr: "len($name) == 1", differs: true },
  { expr: "$name == 1" }, // text field, number literal
  { expr: "$n == '1'" }, // number field, text literal: Python False, SQL would cast
  { expr: '$N == 1' }, // field names are case sensitive in Python (and unknown here)
  { expr: "$n == None" }, // Python False for every row but None; SQL is NULL: write `is None`
  { expr: "$name == 'it\\'s'" },
  { expr: "$n == 1 or" },
  { expr: "$n == 1 and $nope == 2" },
  { expr: "n == 1" }, // a bare name is not a row field
];

function naiveSql(expr: string): string | null {
  try {
    return pyToSql(expr.replace(/\$(\w+)/g, "$1"), FIELDS.map((f) => f.name)) || null;
  } catch {
    return null;
  }
}

const cases = () => ACCEPT.map((e) => ({ script: script(e), sql: pySubsetSql(script(e), FIELDS) }));
const fixture = () => ({
  note: "Generated by ui/src/query/pySubset.test.ts (UPDATE_CONFORMANCE=1 rewrites it). Run through DuckDB and CPython by crates/engine/tests/pyconformance.rs.",
  fields: FIELDS,
  rows: ROWS,
  accept: cases(),
  // `naive` is what the older token-by-token translator (pyToSql, which the editor still uses until UR-20) gives for the same text.
  reject: REJECT.map((r) => ({ script: script(r.expr), differs: r.differs ?? false, naive: naiveSql(r.expr) })),
});
import onDisk from "./conformance.json?raw";

const FILE = new URL("./conformance.json", import.meta.url);

describe("the Python filter subset that SQL may answer", () => {
  it("accepts exactly the listed expressions and rejects everything else", () => {
    for (const c of cases()) expect(c.sql, c.script).not.toBeNull();
    for (const r of REJECT) expect(pySubsetSql(script(r.expr), FIELDS), r.expr).toBeNull();
    // Only the one-line `def calculate(row): return …` shape is in the subset.
    expect(pySubsetSql(`def calculate(row):\n    x = 1\n    return row["n"] == 1\n`, FIELDS)).toBeNull();
    expect(pySubsetSql(`def calculate(row):\n    return row["n"] == 1  # note\n`, FIELDS)).toBeNull();
    expect(pySubsetSql(`def calculate(row): return row["n"] == 1`, FIELDS)).not.toBeNull();
  });

  it("translates to the SQL the engine test compares with CPython", () => {
    expect(pySubsetSql(script("$n == 3 and ($name == 'a' or $name is None)"), FIELDS)).toBe(`"n" = 3 AND ("name" = 'a' OR "name" IS NULL)`);
    expect(pySubsetSql(script("$name in ['it', 'x']"), FIELDS)).toBe(`"name" IN ('it', 'x')`);
  });

  it("keeps conformance.json in step (UPDATE_CONFORMANCE=1 rewrites it)", async () => {
    const text = JSON.stringify(fixture(), null, 1) + "\n";
    if ((globalThis as any).process?.env?.UPDATE_CONFORMANCE) {
      const fs = await import(/* @vite-ignore */ "node:" + "fs");
      fs.writeFileSync(FILE, text);
      return;
    }
    expect(onDisk).toBe(text);
  });
});
