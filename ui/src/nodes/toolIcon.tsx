/** The tool's icon; a tool without one (a plugin, a future tool) gets the wrench. */
export function toolIcon(tool: string): FluentIcon {
  return TOOL_ICONS[tool] ?? WrenchRegular;
}

/** `<ToolIcon tool="buffer" />` */
export function ToolIcon({ tool }: { tool: string }) {
  return createElement(toolIcon(tool));
}
