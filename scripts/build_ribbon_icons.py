#!/usr/bin/env python3
"""Build the ribbon icons (UR-23): docs/design/ribbon-icons/*.svg, ui/src/ribbon/icons/generated.ts and docs/design/ribbon-icons-sample.html.
Run from the repo root: python3 scripts/build_ribbon_icons.py   (needs node for the "today" column: the Fluent icons the ribbon used before)."""
import json, os, re, subprocess, sys
sys.path.insert(0, os.path.dirname(__file__))
import ribbon_icons_lib as L
from ribbon_icons_map import FLUENT2ICON, CMD
LIGHT = {'line': '#1B2A38', 'blue': '#3F8AD9', 'blue-l': '#CFE3F8', 'green': '#3E9B58', 'green-l': '#CBEBD1', 'amber': '#E7A21B', 'amber-l': '#FBE6B0', 'amber-d': '#A56200',
         'red': '#D84C4C', 'red-l': '#F7CACA', 'grey': '#8793A0', 'grey-l': '#E4E8EC', 'grey-d': '#5B6773', 'paper': '#FFFFFF'}
def body(name, small, standalone=False):
    parts = []
    for f in L.I[name]:
        if isinstance(f, L.D):
            if small and standalone: continue
            parts.append(f'<g class="d">{f}</g>')
        else:
            parts.append(f)
    return ''.join(parts)
def with_fallbacks(s):
    return re.sub(r'var\(--ic-([a-z-]+)\)', lambda m: f'var(--ic-{m.group(1)},{LIGHT[m.group(1)]})', s)
def standalone(name, size):
    sw = '2.3' if size == 16 else '1.6'
    b = body(name, size == 16, True).replace('var(--ic-sw)', sw)
    return with_fallbacks(f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 32 32" role="img" aria-label="{name}">{b}</svg>')
OUT = 'docs/design/ribbon-icons'
os.makedirs(OUT, exist_ok=True)
for f in os.listdir(OUT):
    if f.endswith('.svg'): os.remove(os.path.join(OUT, f))
for n in L.I:
    for s in (32, 16): open(f'{OUT}/{n}-{s}.svg', 'w').write(standalone(n, s) + '\n')
# app module
ts = ['// GENERATED by scripts/build_ribbon_icons.py (UR-23). Do not edit: change scripts/ribbon_icons_lib.py and run the script.',
      '// Each value is the inside of a 32 x 32 <svg>; colours are the --ic-* variables of theme/tokens.css; <g class="d"> is fine detail dropped at small sizes.',
      'export const RIBBON_ICONS: Record<string, string> = {']
for n in L.I: ts.append(f'  {json.dumps(n)}: {json.dumps(body(n, False))},')
ts.append('};\n')
os.makedirs('ui/src/ribbon/icons', exist_ok=True)
open('ui/src/ribbon/icons/generated.ts', 'w').write('\n'.join(ts))
# sample page
names = list(L.I)
fl_names = sorted({k for k, v in FLUENT2ICON.items()} | {'ArrowUndoRegular', 'ArrowRedoRegular'})
js = "const R=require('react'),{renderToStaticMarkup:m}=require('react-dom/server'),I=require('@fluentui/react-icons');const o={};for(const n of process.argv.slice(1))o[n]=I[n]?m(R.createElement(I[n])):'';console.log(JSON.stringify(o))"
fl = json.loads(subprocess.check_output(['node', '-e', js] + fl_names))
def flu(n, size):
    if not fl.get(n): return ''
    vb = re.search(r'viewBox="([^"]+)"', fl[n]).group(1)
    paths = ''.join(re.findall(r'<path[^>]*/?>(?:</path>)?', fl[n]))
    return f'<svg class="ic one" width="{size}" height="{size}" viewBox="{vb}" fill="currentColor" aria-hidden="true">{paths}</svg>'
def inline(n, size):
    sw = '2.3' if size == 16 else '1.6'
    b = body(n, size == 16, True).replace('var(--ic-sw)', sw)
    return f'<svg class="ic" width="{size}" height="{size}" viewBox="0 0 32 32" role="img" aria-label="{n}">{b}</svg>'
today = {}
for k, v in FLUENT2ICON.items(): today.setdefault(v, k)
rows = ''
for n in names:
    t = today.get(n)
    rows += f'<tr><th scope="row">{n}</th><td class="b1">{flu(t, 32) + flu(t, 16) if t else "<small>new</small>"}</td>'
    for th in ('light', 'dark'):
        rows += f'<td class="b {th}" data-theme="{th}">{inline(n, 32)}{inline(n, 16)}</td>'
    rows += '</tr>\n'

PALETTE = open('docs/design/ribbon-icons/palette.css').read()
def ribbon(th):
    big = ['add-data', 'basemap', 'select', 'clear-selection', 'identify', 'measure', 'zoom-layer', 'full-extent', 'symbology', 'run-model']
    small = ['attribute-table', 'processing-nodes', 'export', 'coordinate-system', 'remove', 'definition-query', 'layer-add', 'properties']
    b = ''.join(f'<div class="rb">{inline(n, 32)}<span>{n.replace("-", " ").title()}</span></div>' for n in big)
    sm = ''.join(f'<div class="rs">{inline(n, 16)}<span>{n.replace("-", " ").title()}</span></div>' for n in small)
    dis = f'<div class="rs off">{inline("remove", 16)}<span>Disabled</span></div><div class="rs on">{inline("select", 16)}<span>On</span></div>'
    return f'<div class="ribbon {th}" data-theme="{th}"><div class="rg"><div class="rl">{b}</div><div class="gl">Map</div></div><div class="rg"><div class="rc">{sm}</div><div class="gl">Layer</div></div><div class="rg"><div class="rc">{dis}</div><div class="gl">States</div></div></div>'
html = f"""<!doctype html>
<html lang="en" data-theme="light">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Ribbon icon sheet</title>
<!-- UR-23. Generated by scripts/build_ribbon_icons.py. Our own drawings (MIT, with the project); ArcGIS Pro was a style reference only, nothing was traced or copied. -->
<style>
{PALETTE}
:root{{ --surface-1:#F2F5F7; --text:#121A20; --rule:#BCC6CE; }}
body{{margin:0;padding:24px 28px;font:13px/1.45 system-ui,-apple-system,"Segoe UI",sans-serif;color:var(--text);background:#fff}}
h1{{font-size:18px;margin:0 0 4px}} p.n{{margin:0 0 16px;max-width:900px;color:#44515c}}
table{{border-collapse:collapse;margin:8px 0 24px}}
th,td{{border:1px solid var(--rule);padding:6px 12px;vertical-align:middle;text-align:left}}
th{{font-weight:500;min-width:160px;font-size:12px}}
td.b1{{background:var(--surface-1);color:#2b3640}} td.b1 svg,td.b svg{{margin-right:10px;vertical-align:middle}}
td.b.light{{background:var(--surface-1)}} td.b.dark{{background:#1C2126}}
.ic.one{{fill:currentColor}}
.ribbon{{display:flex;gap:2px;padding:6px 8px;border:1px solid var(--rule);margin:10px 0;width:max-content;max-width:100%}}
.ribbon.light{{background:#F2F5F7;color:#121A20;border-color:#BCC6CE}}
.ribbon.dark{{background:#1C2126;color:#EDF1F4;border-color:#3B444C}}
.rg{{display:flex;flex-direction:column;padding:0 8px;border-right:1px solid rgba(128,128,128,.35)}}
.rl,.rc{{display:flex;gap:4px;align-items:flex-start}} .rc{{flex-direction:column;gap:2px}}
.rb{{display:flex;flex-direction:column;align-items:center;gap:4px;width:74px;padding:4px 2px;font-size:12px;text-align:center}}
.rs{{display:flex;align-items:center;gap:6px;padding:2px 6px;font-size:12px}}
.rs.off svg{{opacity:.4}} .rs.off span{{opacity:.55}} .rs.on span{{color:#1E64B4;font-weight:600}}
.ribbon.dark .rs.on span{{color:#7DB4F0}}
.gl{{font-size:11px;opacity:.7;text-align:center;margin-top:4px}}
</style>
</head>
<body>
<h1>Ribbon icons — all {len(names)}</h1>
<p class="n">Every icon the ribbon, the quick access toolbar and the layout Insert rail use, at 32 px (large buttons, rail) and 16 px (small buttons, menus, quick access), light and dark, beside the one-colour Fluent icon each had before. The 16 px drawings drop fine detail and use a heavier line. Rules: docs/DECISIONS.md, "Ribbon icons".</p>
<h1>In a ribbon, with the two states</h1>
{ribbon('light')}{ribbon('dark')}
<table>
<thead><tr><th>Icon</th><th>Before (one colour)</th><th>Light</th><th>Dark</th></tr></thead>
<tbody>
{rows}</tbody>
</table>
</body>
</html>
"""
open('docs/design/ribbon-icons-sample.html', 'w').write(html)
print(len(names), 'icons')
